// === 月齢の隙間を線形補間で埋める ===
// 0〜72ヶ月をすべて 1ヶ月刻みで生成する。
// 末尾（72ヶ月）は 69 と 75 の中間値として補間される。
function fillMonthly(keyData) {
  const filled = [];
  for (let m = 0; m <= 72; m++) {
    // 該当 m を挟む 2点を探す
    let prev = keyData[0];
    let next = keyData[keyData.length - 1];
    for (let i = 0; i < keyData.length - 1; i++) {
      if (keyData[i][0] <= m && keyData[i + 1][0] >= m) {
        prev = keyData[i];
        next = keyData[i + 1];
        break;
      }
    }
    const [pm, pp3, pp10, pp50, pp90, pp97] = prev;
    const [nm, np3, np10, np50, np90, np97] = next;
    if (pm === nm) {
      filled.push({
        ageMonths: m,
        p3: round(pp3),
        p10: round(pp10),
        p50: round(pp50),
        p90: round(pp90),
        p97: round(pp97),
      });
    } else {
      const t = (m - pm) / (nm - pm);
      filled.push({
        ageMonths: m,
        p3: round(pp3 + (np3 - pp3) * t),
        p10: round(pp10 + (np10 - pp10) * t),
        p50: round(pp50 + (np50 - pp50) * t),
        p90: round(pp90 + (np90 - pp90) * t),
        p97: round(pp97 + (np97 - pp97) * t),
      });
    }
  }
  return filled;
}

function round(v) {
  return Math.round(v * 100) / 100;
}

